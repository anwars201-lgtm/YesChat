#!/usr/bin/env tsx
/**
 * Demo-seed generator.
 *
 * Parses `prisma/schema.prisma` via Prisma's DMMF, inspects every non-auth
 * model, and writes a `prisma/seed.demo.ts` that inserts 6 realistic rows
 * per model. Field values are inferred from column name + type using a small
 * heuristic catalog (emails, names, urls, ISO dates, money, lorem text,
 * booleans, enums).
 *
 * Why this exists: the AI otherwise skips seeding or writes one-off demo
 * data inline per feature, so the app boots with empty lists and the "first
 * run" UX feels dead. Running `npm run db:seed:demo` populates every table
 * at once so the app opens with real content.
 *
 * The generated seed uses `seedIfEmpty` from `src/lib/seed.ts`, so it is
 * idempotent — re-running on a populated DB is a no-op. Models with
 * required FK scalars whose parent table is empty are skipped with a
 * log line (not a failure).
 *
 * Run via: `npm run db:seed:generate` (calls `tsx scripts/generate-seed.ts`)
 */
import fs from 'fs';
import path from 'path';

import { getDMMF } from '@prisma/internals';

const SCHEMA_PATH = path.join(__dirname, '..', 'prisma', 'schema.prisma');
const OUTPUT_PATH = path.join(__dirname, '..', 'prisma', 'seed.demo.ts');

const AUTH_MODELS = new Set(['User', 'Session']);
const ROW_COUNT = 6;

type FieldKind = 'scalar' | 'enum' | 'object';

interface GenField {
  name: string;
  type: string;
  kind: FieldKind;
  isRequired: boolean;
  isId: boolean;
  isList: boolean;
  hasDefault: boolean;
  relationFromFields?: string[];
}

interface GenModel {
  name: string;
  fields: GenField[];
}

async function main(): Promise<void> {
  if (!fs.existsSync(SCHEMA_PATH)) {
    console.log(`[seed-gen] schema missing at ${SCHEMA_PATH} — skipping`);
    return;
  }
  const datamodel = fs.readFileSync(SCHEMA_PATH, 'utf8');
  const dmmf = await getDMMF({ datamodel });
  const enums = new Map(dmmf.datamodel.enums.map((e) => [e.name, e.values.map((v) => v.name)]));

  const models: GenModel[] = dmmf.datamodel.models
    .filter((m) => !AUTH_MODELS.has(m.name))
    .map((m) => ({
      name: m.name,
      fields: m.fields.map((f) => ({
        name: f.name,
        type: f.type,
        kind: f.kind as FieldKind,
        isRequired: f.isRequired,
        isId: f.isId,
        isList: f.isList,
        hasDefault: f.hasDefaultValue,
        relationFromFields: f.relationFromFields ? [...f.relationFromFields] : undefined,
      })),
    }));

  if (models.length === 0) {
    console.log('[seed-gen] no non-auth models — nothing to generate');
    return;
  }

  const ordered = topoSortModels(models);
  const body = renderSeedFile(ordered, enums);
  fs.writeFileSync(OUTPUT_PATH, body, 'utf8');
  console.log(`[seed-gen] wrote ${OUTPUT_PATH} (${ordered.length} models)`);
}

/**
 * Order models so a model's parent-relation always appears before its children.
 */
function topoSortModels(models: GenModel[]): GenModel[] {
  const byName = new Map(models.map((m) => [m.name, m]));
  const out: GenModel[] = [];
  const visited = new Set<string>();

  const visit = (m: GenModel): void => {
    if (visited.has(m.name)) return;
    visited.add(m.name);
    for (const f of m.fields) {
      if (f.kind === 'object' && !f.isList && byName.has(f.type)) {
        visit(byName.get(f.type)!);
      }
    }
    out.push(m);
  };

  for (const m of models) visit(m);
  return out;
}

/**
 * Map of FK scalar-field -> parent model name. Used at runtime inside the
 * generated seed to find valid parent ids before inserting children.
 */
function fkMap(m: GenModel): Record<string, string> {
  const map: Record<string, string> = {};
  for (const f of m.fields) {
    if (f.kind !== 'object' || f.isList) continue;
    const scalar = f.relationFromFields?.[0];
    if (!scalar) continue;
    map[scalar] = f.type;
  }
  return map;
}

function renderSeedFile(models: GenModel[], enums: Map<string, string[]>): string {
  const lines: string[] = [];
  lines.push('// AUTO-GENERATED by scripts/generate-seed.ts — do not edit by hand.');
  lines.push('// Re-run `npm run db:seed:generate` after schema changes.');
  lines.push('// eslint-disable @typescript-eslint/no-explicit-any');
  lines.push('');
  lines.push("import { seedIfEmpty, upsertDemoUser } from '../src/lib/seed';");
  lines.push("import { prisma } from '../src/lib/prisma';");
  lines.push('');
  lines.push('async function pickParentIds(model: string, n: number): Promise<string[]> {');
  lines.push('  const delegate = (prisma as any)[model.charAt(0).toLowerCase() + model.slice(1)];');
  lines.push('  if (!delegate) return [];');
  lines.push('  const rows = await delegate.findMany({ select: { id: true }, take: n * 2 });');
  lines.push('  return rows.map((r: { id: string }) => r.id);');
  lines.push('}');
  lines.push('');
  lines.push('async function main(): Promise<void> {');
  lines.push("  console.log('[seed:demo] starting…');");
  lines.push('  const demoUserId = await upsertDemoUser();');
  lines.push('  if (demoUserId) {');
  lines.push("    console.log('[seed:demo] demo user ready:', demoUserId);");
  lines.push('  } else {');
  lines.push("    console.log('[seed:demo] demo user skipped (production)');");
  lines.push('  }');

  for (const m of models) {
    const fks = fkMap(m);
    lines.push('');
    lines.push(`  // ── ${m.name} ────────────────────────────────────────────`);
    lines.push('  {');
    // Resolve parent ids for each FK scalar. Guard clauses use `continue`
    // so multi-FK models check ALL parents (early chaining with `else if`
    // would skip subsequent checks once one FK had rows).
    const fkVars: Record<string, string> = {};
    const guardChecks: string[] = [];
    for (const [scalar, parent] of Object.entries(fks)) {
      const varName = `parents_${scalar}`;
      fkVars[scalar] = varName;
      lines.push(`    const ${varName} = await pickParentIds('${parent}', ${ROW_COUNT});`);
      guardChecks.push(`${varName}.length === 0 ? '${parent} (via ${scalar})' : ''`);
    }
    if (guardChecks.length > 0) {
      lines.push(`    const _missing = [${guardChecks.join(', ')}].filter(Boolean);`);
      lines.push('    if (_missing.length > 0) {');
      lines.push(`      console.log('[seed:demo] ${m.name}: skipped — missing parent rows: ' + _missing.join(', '));`);
      lines.push('    } else {');
    } else {
      lines.push('    {');
    }
    lines.push(`      const rows = Array.from({ length: ${ROW_COUNT} }, (_, i) => ({`);
    for (const f of m.fields) {
      if (f.kind === 'object') continue;
      if (fks[f.name]) {
        const v = fkVars[f.name];
        lines.push(`        ${f.name}: ${v}[i % ${v}.length],`);
        continue;
      }
      const literal = fieldLiteral(f, enums);
      if (literal !== null) lines.push(`        ${f.name}: ${literal},`);
    }
    lines.push('      }));');
    lines.push(`      const res = await seedIfEmpty('${lowerFirst(m.name)}', rows);`);
    lines.push(
      `      console.log(\`[seed:demo] ${m.name}: \${res.seeded ? 'inserted ' + res.count : 'skipped (had ' + res.count + ')'}\`);`,
    );
    lines.push('    }');
    lines.push('  }');
  }

  lines.push('}');
  lines.push('');
  lines.push('main()');
  lines.push('  .catch((e) => { console.error(e); process.exit(1); })');
  lines.push('  .finally(() => prisma.$disconnect());');
  lines.push('');
  return lines.join('\n');
}

function fieldLiteral(f: GenField, enums: Map<string, string[]>): string | null {
  // Relations themselves are set via the scalar FK separately.
  if (f.kind === 'object') return null;
  // Never set IDs with defaults — let Prisma generate them.
  if (f.isId && f.hasDefault) return null;
  // Skip auto-maintained timestamps.
  if (f.hasDefault && (f.name === 'createdAt' || f.name === 'updatedAt')) return null;
  // Skip nullable fields without default — emit undefined (row omits key).
  if (!f.isRequired && !f.hasDefault && f.kind !== 'enum') {
    // For optional fields keep a nullable default when the column is a
    // common one users want populated in demos, else omit entirely.
    // Simplest: omit so Prisma uses null.
    return null;
  }

  if (f.isList) return '[]';

  if (f.kind === 'enum') {
    const values = enums.get(f.type);
    if (!values || values.length === 0) return f.isRequired ? "'UNKNOWN' as any" : 'null';
    return `([${values.map((v) => `'${v}'`).join(', ')}] as const)[i % ${values.length}] as any`;
  }

  const lower = f.name.toLowerCase();
  switch (f.type) {
    case 'String':
      if (lower.includes('email')) return '`user${i + 1}@example.com`';
      if (lower.includes('name') || lower === 'fullname') {
        return "`Demo ${['Alex','Sara','Noah','Ella','Hugo','Maja'][i % 6]} ${i + 1}`";
      }
      if (lower === 'title' || lower.includes('title')) return '`Sample ${i + 1}`';
      if (lower === 'slug') return '`sample-${i + 1}`';
      if (lower.includes('url') || lower.includes('image') || lower.includes('photo') || lower.includes('avatar'))
        return '`https://picsum.photos/seed/${i}/600/400`';
      if (lower.includes('phone')) return '`+1 555 000 ${String(1000 + i).slice(-4)}`';
      if (lower.includes('address')) return '`${i + 1} Main Street, Springfield`';
      if (lower.includes('city')) return "['Springfield','Riverside','Fairview','Madison','Franklin','Clinton'][i % 6]";
      if (lower.includes('country')) return "'United States'";
      if (lower === 'description' || lower.includes('desc') || lower.includes('bio'))
        return "'Short demo description. Replace once real content exists.'";
      if (lower.includes('content') || lower.includes('body') || lower.includes('text') || lower.includes('note'))
        return "'Sample content showing how this field renders in the UI. Lorem ipsum dolor sit amet.'";
      if (lower.includes('status')) return "['active','pending','done','archived'][i % 4]";
      if (lower.includes('color')) return "['#6366F1','#22C55E','#F59E0B','#EF4444','#8B5CF6','#06B6D4'][i % 6]";
      if (lower.includes('token') || lower === 'hash' || lower.includes('secret'))
        return '`demo-${Math.random().toString(36).slice(2)}`';
      return `\`${f.name} demo \${i + 1}\``;
    case 'Int':
    case 'BigInt':
      if (lower.includes('age')) return '18 + i * 3';
      if (lower.includes('price') || lower.includes('amount') || lower.includes('cost')) return '(i + 1) * 49';
      if (lower.includes('count') || lower.includes('quantity') || lower === 'qty') return 'i + 1';
      if (lower.includes('year')) return '2020 + (i % 6)';
      if (lower.includes('order') || lower.includes('position') || lower === 'index') return 'i';
      return 'i + 1';
    case 'Float':
    case 'Decimal':
      if (lower.includes('price') || lower.includes('amount') || lower.includes('cost')) return '(i + 1) * 49.9';
      if (lower.includes('rating') || lower.includes('score')) return '3 + (i % 3) * 0.5';
      if (lower === 'lat' || lower.includes('latitude')) return '59.3 + i * 0.01';
      if (lower === 'lng' || lower === 'long' || lower.includes('longitude')) return '18.0 + i * 0.01';
      return '(i + 1) * 1.1';
    case 'Boolean':
      if (lower.includes('archived') || lower.includes('deleted') || lower.includes('banned')) return 'false';
      return 'i % 2 === 0';
    case 'DateTime':
      if (lower.includes('start')) return 'new Date(Date.now() + i * 86_400_000)';
      if (lower.includes('end') || lower.includes('expir')) return 'new Date(Date.now() + (i + 7) * 86_400_000)';
      return 'new Date(Date.now() - i * 86_400_000)';
    case 'Json':
      return '{ note: `meta-${i + 1}` }';
    default:
      return f.isRequired ? 'null as never' : 'null';
  }
}

function lowerFirst(name: string): string {
  return name.charAt(0).toLowerCase() + name.slice(1);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
