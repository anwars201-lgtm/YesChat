/**
 * Prisma → Dart model rendering (pure: no Prisma RPC, no process env).
 *
 * `generate-dart-models.ts` is the `generator dart` provider Prisma spawns on
 * every `prisma generate`; it hands the DMMF models to `generateDartModels`
 * below. Keeping the rendering here lets the repo unit-test it without a
 * Prisma parent process (see packages/project-template/tests/).
 *
 * Preserve rule (starter workspaces only, `preserveHandWritten: true`): a
 * target file that already exists WITHOUT the generated header is a
 * starter-owned hand-written model (e.g. todo-reminders' `todo.dart` with
 * `TodoStats` + `isOverdue`). It is left untouched and reported instead of
 * being clobbered — that clobbering is what broke every starter APK build
 * ("Type 'TodoStats' not found"). Non-starter projects never set the option,
 * so their output is byte-identical to the historical generator.
 */
import fs from 'fs';
import path from 'path';

import type { DMMF } from '@prisma/generator-helper';

export const GENERATED_HEADER_LINE = '// GENERATED CODE - DO NOT MODIFY BY HAND';
export const GENERATED_HEADER = `${GENERATED_HEADER_LINE}\n// This file was generated by Prisma to Dart generator.\n`;

/** Models the base template owns in hand-written form — never generated. */
export const SKIPPED_MODELS: ReadonlySet<string> = new Set(['User', 'Session']);

export interface GeneratorLog {
  info(message: string): void;
  warn(message: string): void;
}

export interface GenerateDartModelsOptions {
  /** Leave hand-written (header-less) target files alone instead of overwriting them. */
  preserveHandWritten?: boolean;
  log?: GeneratorLog;
}

export interface PreservedDartModel {
  file: string;
  model: string;
  /** Scalar/enum schema field names that do not appear anywhere in the preserved file. */
  missingFields: string[];
}

export interface GenerateDartModelsResult {
  written: string[];
  preserved: PreservedDartModel[];
}

export function dartFileNameFor(modelName: string): string {
  return modelName.replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase() + '.dart';
}

export function isGeneratedDartModel(content: string): boolean {
  return content.startsWith(GENERATED_HEADER_LINE);
}

export function renderDartModel(model: DMMF.Model): string {
  const className = model.name;

  let imports = '';
  let fields = '';
  let fromJsonMap = '';
  let toJsonMap = '';
  let constructorArgs = '';
  let copyWithArgs = '';
  let copyWithMap = '';

  // Shared generated resources expose two response-only access fields that
  // are computed by the backend (they are deliberately not Prisma columns).
  // Detect the platform-owned shareCode column and materialize those wire
  // fields in Dart so member screens cannot accidentally show owner controls.
  const fieldNames = new Set(model.fields.map((field) => field.name));
  const hasSharedAccessProjection = fieldNames.has('shareCode');

  const relationTypes = new Set<string>();

  for (const field of model.fields) {
    if (field.kind === 'object') {
      relationTypes.add(field.type);
    }
  }

  if (hasSharedAccessProjection) {
    fields += '  final String? accessRole;\n  final bool canManage;\n';
    constructorArgs += '    this.accessRole,\n    this.canManage = false,\n';
    fromJsonMap +=
      "      accessRole: json['accessRole'] as String?,\n" +
      "      canManage: (json['canManage'] as bool?) ?? false,\n";
    toJsonMap += "      'accessRole': accessRole,\n      'canManage': canManage,\n";
    copyWithArgs += '    String? accessRole,\n    bool? canManage,\n';
    copyWithMap +=
      '      accessRole: accessRole ?? this.accessRole,\n' +
      '      canManage: canManage ?? this.canManage,\n';
  }

  for (const rel of relationTypes) {
    if (rel !== className && rel !== 'User' && rel !== 'Session') {
      imports += `import '${dartFileNameFor(rel)}';\n`;
    } else if (rel === 'User') {
      imports += `import 'user.dart';\n`;
    }
  }

  if (imports.length > 0) {
    imports += '\n';
  }

  for (const field of model.fields) {
    // Relations (objects) are always optional in the JSON payload unless explicitly included,
    // so we must make them nullable in Dart to avoid fromJson crashes.
    // Lists are never optional in Dart, they default to empty arrays.
    const isOptional = (!field.isRequired || field.kind === 'object') && !field.isList;

    let dartType = 'String';

    if (field.kind === 'scalar') {
      switch (field.type) {
        case 'String':
          dartType = 'String';
          break;
        case 'Int':
          dartType = 'int';
          break;
        case 'Float':
        case 'Decimal':
          dartType = 'double';
          break;
        case 'Boolean':
          dartType = 'bool';
          break;
        case 'DateTime':
          dartType = 'DateTime';
          break;
        case 'Json':
          dartType = 'Map<String, dynamic>';
          break;
        default:
          dartType = 'String';
          break;
      }
    } else if (field.kind === 'object') {
      dartType = field.type;
    } else if (field.kind === 'enum') {
      dartType = 'String'; // Simplify enums to Strings for JSON compat
    }

    const baseDartType = dartType;

    if (field.isList) {
      dartType = `List<${dartType}>`;
    }

    const finalDartType = isOptional ? `${dartType}?` : dartType;
    fields += `  final ${finalDartType} ${field.name};\n`;
    constructorArgs += `    ${isOptional ? '' : 'required '}this.${field.name},\n`;
    copyWithArgs += `    ${dartType}? ${field.name},\n`;
    copyWithMap += `      ${field.name}: ${field.name} ?? this.${field.name},\n`;

    // JSON Mapping
    //
    // Every required-scalar read below falls back to a type-appropriate
    // zero when the JSON key is missing or null. This keeps the Dart
    // field non-nullable (so UI code compiles unchanged) while
    // tolerating partial projections the backend might emit via
    // `select: { id: true, name: true }` on nested relations — without
    // the fallback the projected User blob would crash
    // `json['email'] as String` and the entire mutation flow surfaces
    // as a generic "could not save" error in the UI. See
    // docs/adr (pending) for the full mismatch classification.
    if (field.isList) {
      if (field.kind === 'object') {
        fromJsonMap += `      ${field.name}: (json['${field.name}'] as List<dynamic>?)?.map((e) => ${baseDartType}.fromJson(e as Map<String, dynamic>)).toList() ?? [],\n`;
        toJsonMap += `      '${field.name}': ${field.name}.map((e) => e.toJson()).toList(),\n`;
      } else {
        fromJsonMap += `      ${field.name}: (json['${field.name}'] as List<dynamic>?)?.map((e) => e as ${baseDartType}).toList() ?? [],\n`;
        toJsonMap += `      '${field.name}': ${field.name},\n`;
      }
    } else if (field.kind === 'object') {
      if (isOptional) {
        fromJsonMap += `      ${field.name}: json['${field.name}'] != null ? ${baseDartType}.fromJson(json['${field.name}'] as Map<String, dynamic>) : null,\n`;
        toJsonMap += `      '${field.name}': ${field.name}?.toJson(),\n`;
      } else {
        fromJsonMap += `      ${field.name}: ${baseDartType}.fromJson(json['${field.name}'] as Map<String, dynamic>),\n`;
        toJsonMap += `      '${field.name}': ${field.name}.toJson(),\n`;
      }
    } else if (field.type === 'DateTime') {
      if (isOptional) {
        fromJsonMap += `      ${field.name}: json['${field.name}'] != null ? DateTime.parse(json['${field.name}'].toString()) : null,\n`;
        toJsonMap += `      '${field.name}': ${field.name}?.toIso8601String(),\n`;
      } else {
        fromJsonMap += `      ${field.name}: json['${field.name}'] != null ? DateTime.parse(json['${field.name}'].toString()) : DateTime.fromMillisecondsSinceEpoch(0),\n`;
        toJsonMap += `      '${field.name}': ${field.name}.toIso8601String(),\n`;
      }
    } else if (field.type === 'Float' || field.type === 'Decimal') {
      if (isOptional) {
        fromJsonMap += `      ${field.name}: json['${field.name}'] != null ? (json['${field.name}'] as num).toDouble() : null,\n`;
      } else {
        fromJsonMap += `      ${field.name}: (json['${field.name}'] as num?)?.toDouble() ?? 0.0,\n`;
      }
      toJsonMap += `      '${field.name}': ${field.name},\n`;
    } else if (field.type === 'Int') {
      if (isOptional) {
        fromJsonMap += `      ${field.name}: json['${field.name}'] != null ? (json['${field.name}'] as num).toInt() : null,\n`;
      } else {
        fromJsonMap += `      ${field.name}: (json['${field.name}'] as num?)?.toInt() ?? 0,\n`;
      }
      toJsonMap += `      '${field.name}': ${field.name},\n`;
    } else if (isOptional) {
      fromJsonMap += `      ${field.name}: json['${field.name}'] as ${finalDartType},\n`;
      toJsonMap += `      '${field.name}': ${field.name},\n`;
    } else {
      // Required scalar (String, Boolean, enum-as-String, Json-as-Map).
      // Fall back to a type-appropriate empty value so partial projections
      // don't raise `type 'Null' is not a subtype of type 'X'`.
      let fallback: string;
      switch (dartType) {
        case 'String':
          fallback = "''";
          break;
        case 'bool':
          fallback = 'false';
          break;
        case 'Map<String, dynamic>':
          fallback = '<String, dynamic>{}';
          break;
        default:
          fallback = `${dartType}()`;
          break;
      }
      fromJsonMap += `      ${field.name}: (json['${field.name}'] as ${dartType}?) ?? ${fallback},\n`;
      toJsonMap += `      '${field.name}': ${field.name},\n`;
    }
  }

  return `${GENERATED_HEADER}${imports}
class ${className} {
${fields}
  const ${className}({
${constructorArgs}  });

  factory ${className}.fromJson(Map<String, dynamic> json) {
    return ${className}(
${fromJsonMap}    );
  }

  Map<String, dynamic> toJson() {
    return {
${toJsonMap}    };
  }

  ${className} copyWith({
${copyWithArgs}  }) {
    return ${className}(
${copyWithMap}    );
  }
}
`;
}

const silentLog: GeneratorLog = { info: () => {}, warn: () => {} };

export function generateDartModels(
  models: ReadonlyArray<DMMF.Model>,
  outputDir: string,
  options: GenerateDartModelsOptions = {},
): GenerateDartModelsResult {
  const log = options.log ?? silentLog;
  const preserveHandWritten = options.preserveHandWritten === true;

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const written: string[] = [];
  const preserved: PreservedDartModel[] = [];

  for (const model of models) {
    // Skip User and Session to avoid overwriting template auth models
    if (SKIPPED_MODELS.has(model.name)) {
      continue;
    }

    const fileName = dartFileNameFor(model.name);
    const filePath = path.join(outputDir, fileName);

    if (preserveHandWritten && fs.existsSync(filePath)) {
      const existing = fs.readFileSync(filePath, 'utf8');
      if (!isGeneratedDartModel(existing)) {
        const missingFields = model.fields
          .filter((field) => field.kind !== 'object' && !new RegExp(`\\b${field.name}\\b`).test(existing))
          .map((field) => field.name);
        preserved.push({ file: fileName, model: model.name, missingFields });
        log.warn(
          `[generate-dart-models] PRESERVED hand-written ${fileName} — starter-owned model file for ${model.name}, not regenerated. ` +
            (missingFields.length
              ? `Schema fields not found in the file: ${missingFields.join(', ')}.`
              : 'Every schema field is present.'),
        );
        continue;
      }
    }

    fs.writeFileSync(filePath, renderDartModel(model));
    written.push(fileName);
  }

  return { written, preserved };
}
