// Pre-built verification helper for protected backend routes.
//
// Why this exists: agents otherwise rewrite auth-aware test scripts from
// scratch every project, iterating 5–8 times to discover the X-API-Key +
// register-then-login + JWT-bearer pattern via 401 errors. Using this
// helper compresses that to a single tool call.
//
// Usage from a verification script:
//
//   const { setup } = require('./lib/verify');
//   const { request } = await setup({});  // defaults: demo@example.com / Demo123!
//   for (const path of ['/shopping-lists', '/shopping-lists/recent']) {
//     const r = await request(path);
//     if (r.status === 404) throw new Error(`${path} → 404`);
//     if (!r.ok) throw new Error(`${path} → ${r.status} ${JSON.stringify(r.body)}`);
//     console.log(`${path} → ${r.status}`);
//   }
//
// The helper assumes /auth/register and /auth/login exist on this backend
// (template default). Override via setup({ registerPath, loginPath }) if
// your project uses different paths.
//
// Reads PROJECT_API_KEY from process.env. If empty, throws with a clear
// "missing config" message — never silently fails open.

const DEFAULT_BASE = process.env.VERIFY_BASE_URL || 'http://localhost:3000';

async function setup({
  testUser = { email: 'demo@example.com', password: 'Demo123!', name: 'Demo' },
  registerPath = '/auth/register',
  loginPath = '/auth/login',
  baseUrl = DEFAULT_BASE,
} = {}) {
  const apiKey = process.env.PROJECT_API_KEY;
  if (!apiKey) {
    throw new Error(
      'PROJECT_API_KEY not in env — verify.cjs cannot authenticate. Check that backend/.env was generated by start.sh and that the container env has PROJECT_API_KEY set.',
    );
  }
  const baseHeaders = { 'Content-Type': 'application/json', 'X-API-Key': apiKey };

  // Idempotent register. /auth/register returns:
  //   201 on success
  //   409 if email already registered (treated as "user exists, log in instead")
  //   422 / 400 on validation errors — surface as fatal
  const reg = await fetch(baseUrl + registerPath, {
    method: 'POST',
    headers: baseHeaders,
    body: JSON.stringify(testUser),
  });
  if (!reg.ok && reg.status !== 409) {
    const text = await reg.text().catch(() => '<no body>');
    throw new Error(`register ${reg.status}: ${text.slice(0, 300)}`);
  }

  // Login → JWT.
  const login = await fetch(baseUrl + loginPath, {
    method: 'POST',
    headers: baseHeaders,
    body: JSON.stringify({ email: testUser.email, password: testUser.password }),
  });
  if (!login.ok) {
    const text = await login.text().catch(() => '<no body>');
    throw new Error(`login ${login.status}: ${text.slice(0, 300)}`);
  }
  const data = await login.json();
  const token = data.accessToken || data.token || data.jwt;
  if (!token) {
    throw new Error(`login ok but no token in response: ${JSON.stringify(data).slice(0, 300)}`);
  }

  async function request(path, options = {}) {
    const headers = {
      ...baseHeaders,
      Authorization: `Bearer ${token}`,
      ...(options.headers || {}),
    };
    const res = await fetch(baseUrl + path, { ...options, headers });
    const text = await res.text();
    let body;
    try {
      body = text ? JSON.parse(text) : null;
    } catch {
      body = text;
    }
    return { status: res.status, ok: res.ok, body };
  }

  return { token, request, testUser };
}

module.exports = { setup };
